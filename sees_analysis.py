while x < len(allData):
    point = 0
    sublist_ground = []
    sublist_model = []
    while point < 100:
        sublist_ground.append(allData['crosswalked label (student data)'][x])
        sublist_model.append(allData['Model label (worldcover)'][x])
        x += 1
        point += 1
    PSU_classes_ground.append(sublist_ground)
    PSU_classes_model.append(sublist_model)

